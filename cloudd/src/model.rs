#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, ToSchema)]
pub struct ProjectSpec {
    #[serde(default = "one")]
    pub schema: u32,
    pub project: String,
    #[serde(default)]
    pub workspace: WorkspaceSpec,
    #[serde(default)]
    pub agents: Vec<String>,
    /// Capability names; in slice 1 a capability resolves to the installed app that `provides` it and becomes
    /// the route `http://<capability>.gate` on the project gate.
    #[serde(default)]
    pub capabilities: Vec<String>,
    /// Owner's note: what this project is and what happens in it — so there is a human mark besides a name like
    /// `alpha`. The core does not interpret it; up to 2000 characters, an empty one on apply becomes absence.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
    /// Service project (ADR-006: the `scratch` workspace of quick chats): served like the others, but shown in the
    /// project list (`GET /api/projects`) only with `?all=1` — Desktop and the "Workplaces" tree do not see it.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub hidden: bool,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, ToSchema)]
pub struct WorkspaceSpec {
    #[serde(default = "default_runtime")]
    pub runtime: Runtime,
    #[serde(default = "default_cpu")]
    pub cpu: u32,
    /// In GiB; YAML allows `8GiB`/`8`.
    #[serde(default = "default_memory", deserialize_with = "de_gib", serialize_with = "ser_gib")]
    pub memory: u32,
    #[serde(default = "default_home", deserialize_with = "de_gib", serialize_with = "ser_gib")]
    pub home: u32,
    #[serde(default)]
    pub image: Option<String>,
}

impl Default for WorkspaceSpec {
    fn default() -> Self {
        Self { runtime: default_runtime(), cpu: default_cpu(), memory: default_memory(), home: default_home(), image: None }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "kebab-case")]
pub enum Runtime {
    Incus,
    IncusNesting,
    IncusVm,
}
impl Runtime {
    pub fn as_param(&self) -> &'static str {
        match self {
            Runtime::Incus => "incus",
            Runtime::IncusNesting => "incus-nesting",
            Runtime::IncusVm => "incus-vm",
        }
    }
}

fn one() -> u32 { 1 }
fn default_runtime() -> Runtime { Runtime::IncusNesting }
fn default_cpu() -> u32 { 2 }
fn default_memory() -> u32 { 4 }
fn default_home() -> u32 { 50 }

fn de_gib<'de, D: serde::Deserializer<'de>>(d: D) -> Result<u32, D::Error> {
    #[derive(Deserialize)]
    #[serde(untagged)]
    enum V { N(u32), S(String) }
    match V::deserialize(d)? {
        V::N(n) => Ok(n),
        V::S(s) => {
            let t = s.trim().trim_end_matches("GiB").trim_end_matches("Gi").trim_end_matches('G').trim();
            t.parse().map_err(|_| serde::de::Error::custom(format!("ожидалось число GiB, получено {s:?}")))
        }
    }
}
fn ser_gib<S: serde::Serializer>(v: &u32, s: S) -> Result<S::Ok, S::Error> {
    s.serialize_str(&format!("{v}GiB"))
}

// ---------- app manifest (2.6) ----------

#[derive(Debug, Clone, Serialize, Deserialize, ToSchema)]
pub struct AppManifest {
    #[serde(default = "one")]
    pub schema: u32,
    pub name: String,
    #[serde(default)]
    pub title: Option<String>,
    #[serde(default)]
    pub description: Option<String>,
    /// Manifest text translations by the Desktop UI language (keys en/ru/uk/es): `i18n.<lang>.description` is shown,
    /// without a translation — `description`. Empty for imported manifests: their descriptions are English, from upstream.
    #[serde(default, skip_serializing_if = "std::collections::BTreeMap::is_empty")]
    pub i18n: std::collections::BTreeMap<String, I18nText>,
    #[serde(default)]
    pub icon: Option<String>,
    #[serde(default, rename = "type")]
    pub kind: AppKind,
    /// Compose path relative to the manifest directory (empty for `type:
    /// external`).
    #[serde(default)]
    pub compose: String,
    #[serde(default)]
    pub provides: Vec<String>,
    #[serde(default)]
    pub requires: Vec<String>,
    #[serde(default)]
    pub route: RouteSpec,
    #[serde(default)]
    pub auth: Option<String>,
    /// Environment variables generated by the core → secret store → the
    /// stack `.env`.
    #[serde(default)]
    pub env: std::collections::BTreeMap<String, EnvSpec>,
    /// What to snapshot and back up (`tank/apps/<name>`); the core creates the
    /// `APP_DATA_DIR` directory.
    #[serde(default)]
    pub data: Vec<String>,
    /// Healthcheck URL inside the app network (`http://<service>:<port>/path`).
    #[serde(default)]
    pub health: Option<String>,
    /// Where routes lead: the service and port inside `<app>-net` (for the edge
    /// and the gate).
    #[serde(default)]
    pub endpoint: Endpoint,
    #[serde(default)]
    pub hooks: Hooks,
    /// External capability provider (`type: external`): a service outside this server. The project gate proxies
    /// `http://<cap>.gate` to the address from the `url_env` setting and inserts the key from `key_env`; hooks work as for a
    /// regular provider.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub external: Option<ExternalSpec>,
    /// `manual` (hand-written) | `runtipi` (importer); the importer leaves
    /// manual alone.
    #[serde(default = "manual")]
    pub origin: String,
    /// Upstream catalog metadata: source, author, version, categories.
    #[serde(default)]
    pub upstream: Option<serde_json::Value>,
    /// App settings from the catalog (form_fields) — for the UI; the values live in
    /// `env`.
    #[serde(default)]
    pub settings: Vec<serde_json::Value>,
    /// Mounts the host's docker.sock — show a warning (the platform trust level).
    #[serde(default)]
    pub host_docker_socket: bool,
    #[serde(default)]
    pub notes: Vec<String>,
    /// Screenshots from the catalog (URLs); shown in the app card.
    #[serde(default)]
    pub gallery: Vec<String>,
    /// Long description (markdown) — the path to a file next to the manifest
    /// (`./description.md`).
    #[serde(default)]
    pub readme: Option<String>,
    #[serde(default)]
    pub website: Option<String>,
    #[serde(default)]
    pub tags: Vec<String>,
    /// Sign-in data (the "Access" section in Desktop): what the core knows about the app's login
    /// and password.
    #[serde(default)]
    pub login: LoginSpec,
    /// Curated "Recommended" list (store/recommended.yaml): the place on the shelf and the reason. Mixed in when the manifest
    /// is read.
    #[serde(default)]
    pub recommended: Option<Recommended>,
}

#[derive(Debug, Clone, Serialize, Deserialize, ToSchema)]
pub struct Recommended {
    pub rank: u32,
    pub reason: String,
    /// Reason translations by UI language (`i18n.<lang>.reason`).
    #[serde(default, skip_serializing_if = "std::collections::BTreeMap::is_empty")]
    pub i18n: std::collections::BTreeMap<String, I18nText>,
}

/// Translatable texts of the manifest and the "Recommended" list in
/// one language.
#[derive(Debug, Clone, Default, Serialize, Deserialize, ToSchema)]
pub struct I18nText {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reason: Option<String>,
}

fn manual() -> String { "manual".into() }

/// How to sign in to the app. `user`/`password` — a variable name from `env` (the value is taken from the secret store or
/// settings) or a literal. Filled by the importer (see `importer::derive_login`), refined by a `login.yaml` file next to
/// the manifest.
#[derive(Debug, Clone, Default, Serialize, Deserialize, ToSchema)]
pub struct LoginSpec {
    #[serde(default)]
    pub mode: LoginMode,
    #[serde(default)]
    pub user: Option<String>,
    #[serde(default)]
    pub password: Option<String>,
    /// Sign-in page path relative to the app URL.
    #[serde(default)]
    pub path: Option<String>,
    #[serde(default)]
    pub note: Option<String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "lowercase")]
pub enum LoginMode {
    /// The core knows the login and password: generated at install or set in the
    /// settings.
    Generated,
    /// Default password from the app image (a literal) — change after the first sign-in.
    Default,
    /// Sign-in is set up in the app itself (first-run wizard) or there is none — the catalog cannot tell
    /// them apart.
    #[default]
    App,
    /// No sign-in: access is limited by the Cloud
    /// OS network.
    None,
    /// Sign-in through an external service
    /// (OAuth etc.).
    External,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "lowercase")]
pub enum AppKind {
    #[default]
    App,
    System,
    /// External capability provider: a service outside this server, the core starts nothing (see
    /// `AppManifest::external`).
    External,
}

